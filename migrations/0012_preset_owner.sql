-- 0012_preset_owner — 프리셋에 소유자를 준다 (BE-25)
--
-- `POST /api/presets`는 **인증 호출이 0건**이었고 쿼리가
-- `ON CONFLICT(id) DO UPDATE`라, **id만 알면 남이 만든 프리셋을 아무나 덮어썼다.**
-- 0006이 심은 내장 프리셋 5종도 같은 테이블이라 함께 뚫려 있었다.
--
-- 프리셋은 이 제품의 핵심 컨셉이다([[Context]]) — 실무에서 넘어오는 건 색상 값이
-- 아니라 이미지라, 추출해 프리셋으로 **쌓는** 흐름이 있어야 실제 문제를 푼다.
-- 그 축적물을 아무나 덮어쓸 수 있으면 축적이 성립하지 않는다. 게다가 프리셋 색은
-- 참가자 화면에 그대로 렌더되므로 **덮어쓰기가 곧 남의 행사 페이지 색을 바꾸는 것**이다.
--
-- NULL = 주인 없는 프리셋 = **내장(공용)**이다. 그래서 이 컬럼 하나가 두 가지를
-- 동시에 정한다: 누가 고칠 수 있는가(주인만), 누구에게 보이는가(공용은 모두에게).
-- `events.owner_id`가 데모와 사용자 이벤트를 가르는 방식과 같은 규칙이라
-- 새 개념을 들이지 않는다.
--
-- 기존 행은 전부 NULL로 남는다 — 내장 5종은 그게 맞고, 그 사이 만들어진 추출본이
-- 있다면 **주인이 없으므로 아무도 덮어쓸 수 없다**(잠기는 쪽이 안전한 기본값이다).
--
-- CASCADE인 이유: 계정을 지우면 그 사람의 이벤트가 CASCADE로 사라지므로(0010)
-- 프리셋만 남겨 둘 이유가 없다. 남의 이벤트가 그 프리셋을 참조 중이면
-- `events.preset_id`의 ON DELETE SET NULL이 받아 준다(빌트인 폴백으로 그려진다).

ALTER TABLE brand_presets ADD COLUMN owner_id INTEGER REFERENCES users(id) ON DELETE CASCADE;

-- 목록 조회가 "공용 + 내 것"으로 걸러지므로 이 인덱스를 탄다.
CREATE INDEX idx_presets_owner ON brand_presets(owner_id);
